//! Report templates for Markdown generation
//!
//! This module provides Handlebars templates and helper functions for
//! generating human-readable Markdown reports from simulation results.

use crate::{
    DeterminismCertificate, FullSimulationReport, GttHypothesisResult, HypothesisInterpretation,
    HypothesisReport, PomSummary, PomValidationReport, ReportConfig,
};
use sim_core::pom::PomValidationSuite;
use std::fmt::Write;

/// Generate POM validation report in Markdown
#[must_use]
pub fn pom_validation_template(report: &PomValidationReport) -> String {
    let config = &report.config;
    let summary = &report.summary;
    let suite = &report.suite;

    let mut md = String::new();

    // Header
    let _ = write!(md, "# {}\n\n", config.title);
    md.push_str("**Report Type:** POM Validation Report\n\n");
    let _ = write!(
        md,
        "**Generated:** {}\n\n",
        report.generated_at.format(&config.date_format)
    );
    let _ = write!(md, "**Author:** {}\n\n", config.author);
    let _ = write!(md, "**Version:** {}\n\n", config.version);

    write_pom_executive_summary(&mut md, summary, suite);
    write_pom_category_breakdown(&mut md, summary);
    write_failed_targets(&mut md, suite);

    // Methodology
    md.push_str("## Methodology\n\n");
    md.push_str("This report validates simulation outputs against empirical patterns ");
    md.push_str("defined in the Pattern-Oriented Modeling (POM) framework. Each target ");
    md.push_str("represents a known empirical pattern that the simulation should reproduce.\n\n");
    md.push_str("### Acceptance Criteria\n\n");
    md.push_str("- **P0 (Critical):** Must pass for research validity\n");
    md.push_str("- **P1 (Important):** Should pass for confidence\n");
    md.push_str("- **P2 (Optional):** Nice to have\n\n");

    // Footer
    md.push_str("---\n\n");
    let _ = writeln!(md, "*Generated by sim-report v{}*", config.version);

    md
}

fn write_pom_executive_summary(md: &mut String, summary: &PomSummary, suite: &PomValidationSuite) {
    md.push_str("## Executive Summary\n\n");
    md.push_str("| Metric | Value |\n");
    md.push_str("|--------|-------|\n");
    let _ = writeln!(md, "| Total Targets | {} |", summary.total_targets);
    let _ = writeln!(
        md,
        "| Passed | {} ({:.1}%) |",
        summary.passed,
        summary.pass_rate * 100.0
    );
    let _ = writeln!(md, "| Failed | {} |", summary.failed);
    let _ = writeln!(
        md,
        "| P0 (Critical) Passed | {}/{} ({:.1}%) |",
        summary.p0_passed,
        summary.p0_targets,
        summary.p0_pass_rate * 100.0
    );
    let _ = write!(md, "| Overall Score | {:.0}/100 |\n\n", suite.overall_score);

    // TAG: surface=simulation owner=research-team rule=SIM-001
    // Validation Status
    if summary.p0_pass_rate >= 1.0 {
        md.push_str("✅ **VALIDATION PASSED** - All critical (P0) targets met.\n\n");
    } else if summary.p0_pass_rate >= 0.8 {
        md.push_str("🟡 **VALIDATION CONDITIONAL** - Most critical targets met.\n\n");
    } else {
        md.push_str("❌ **VALIDATION FAILED** - Critical targets not met.\n\n");
    }
}

fn write_pom_category_breakdown(md: &mut String, summary: &PomSummary) {
    md.push_str("## Category Breakdown\n\n");
    md.push_str("| Category | Total | Passed | Pass Rate | Status |\n");
    md.push_str("|----------|-------|--------|-----------|--------|\n");

    for cat_summary in &summary.category_summaries {
        let status = if cat_summary.pass_rate >= 0.9 {
            "✅"
        } else if cat_summary.pass_rate >= 0.7 {
            "🟡"
        } else {
            "❌"
        };
        let _ = writeln!(
            md,
            "| {} | {} | {} | {:.1}% | {} |",
            cat_summary.category,
            cat_summary.total,
            cat_summary.passed,
            cat_summary.pass_rate * 100.0,
            status
        );
    }
    md.push('\n');
}

fn write_failed_targets(md: &mut String, suite: &PomValidationSuite) {
    let failed_targets: Vec<_> = suite
        .categories
        .values()
        .flat_map(|c| &c.targets)
        .filter(|t| !t.passed)
        .collect();

    if !failed_targets.is_empty() {
        md.push_str("## Failed Targets\n\n");
        md.push_str("| ID | Name | Observed | Expected Range | Priority |\n");
        md.push_str("|----|------|----------|----------------|----------|\n");

        for target in failed_targets {
            let priority = target.priority.as_str();
            let _ = writeln!(
                md,
                "| {} | {} | {:.3} | [{:.2}, {:.2}] | {} |",
                // TAG: surface=simulation owner=research-team rule=SIM-001
                target.target_id,
                target.name,
                target.observed,
                target.acceptance_band.0,
                target.acceptance_band.1,
                priority
            );
        }
        md.push('\n');
    }
}

fn write_hypothesis_header(md: &mut String, report: &HypothesisReport) {
    let config = &report.config;
    let _ = write!(md, "# {}\n\n", config.title);
    md.push_str("**Report Type:** GTT Hypothesis Test Report\n\n");
    let _ = write!(
        md,
        // TAG: surface=simulation owner=research-team rule=SIM-001
        "**Generated:** {}\n\n",
        report.generated_at.format(&config.date_format)
    );
    let _ = write!(md, "**Author:** {}\n\n", config.author);
    let _ = write!(md, "**Version:** {}\n\n", config.version);
}

fn write_hypothesis_statement(md: &mut String) {
    md.push_str("## Hypothesis\n\n");
    md.push_str("> **H₁:** Protocol ON (decentralized verification) increases trust (τ) ");
    md.push_str("compared to Protocol OFF (centralized oracle).\n\n");
    md.push_str("> **H₀:** Protocol ON does not increase trust compared to Protocol OFF.\n\n");
}

fn write_hypothesis_conclusion(
    md: &mut String,
    result: &GttHypothesisResult,
    interp: &HypothesisInterpretation,
) {
    md.push_str("## Conclusion\n\n");
    if result.hypothesis_supported {
        md.push_str("✅ **HYPOTHESIS SUPPORTED**\n\n");
    } else {
        md.push_str("❌ **HYPOTHESIS NOT SUPPORTED**\n\n");
    }
    let _ = write!(md, "{}\n\n", interp.conclusion);
}

fn write_results_summary(
    md: &mut String,
    result: &GttHypothesisResult,
    interp: &HypothesisInterpretation,
) {
    md.push_str("## Results Summary\n\n");
    md.push_str("| Metric | Value |\n");
    md.push_str("|--------|-------|\n");
    let _ = writeln!(md, "| Runs per condition | {} |", result.n_runs);
    let _ = writeln!(md, "| Master seed | {} |", result.seed);
    let _ = writeln!(
        md,
        "| Effect size (Cohen's d) | {:.3} |",
        result.effect_size
    );
    let _ = writeln!(
        md,
        "| 95% CI | [{:.3}, {:.3}] |",
        result.effect_size_ci_lower, result.effect_size_ci_upper
    );
    let _ = writeln!(md, "| t-statistic | {:.3} |", result.t_statistic);
    let _ = writeln!(md, "| p-value | {:.4} |", result.p_value);
    let _ = write!(md, "| Effect magnitude | {} |\n\n", interp.effect_magnitude);
}

fn write_condition_comparison(md: &mut String, result: &GttHypothesisResult) {
    md.push_str("## Condition Comparison\n\n");
    md.push_str("### Protocol ON (Decentralized)\n\n");
    let _ = writeln!(md, "- **Sample size:** n = {}", result.protocol_on.n);
    let _ = writeln!(md, "- **Mean trust (τ):** {:.4}", result.protocol_on.mean);
    let _ = write!(
        md,
        "- **Standard deviation:** {:.4}\n\n",
        result.protocol_on.std
    );

    md.push_str("### Protocol OFF (Centralized)\n\n");
    let _ = writeln!(md, "- **Sample size:** n = {}", result.protocol_off.n);
    let _ = writeln!(md, "- **Mean trust (τ):** {:.4}", result.protocol_off.mean);
    let _ = write!(
        md,
        "- **Standard deviation:** {:.4}\n\n",
        result.protocol_off.std
    );

    md.push_str("### Difference\n\n");
    let diff = result.protocol_on.mean - result.protocol_off.mean;
    let _ = writeln!(md, "- **Absolute difference:** {diff:.4}");
    let _ = write!(
        md,
        "- **Relative improvement:** {:.1}%\n\n",
        (diff / result.protocol_off.mean) * 100.0
    );
}

fn write_statistical_interpretation(
    md: &mut String,
    result: &GttHypothesisResult,
    interp: &HypothesisInterpretation,
) {
    md.push_str("## Statistical Interpretation\n\n");
    let _ = write!(
        md,
        // TAG: surface=simulation owner=research-team rule=SIM-001
        "**Effect Size:** {} (Cohen's d = {:.2})\n\n",
        interp.effect_magnitude, result.effect_size
    );
    let _ = write!(
        md,
        "**Statistical Significance:** {}\n\n",
        interp.significance
    );
    let _ = write!(
        md,
        "**Practical Significance:** {}\n\n",
        interp.practical_significance
    );
}

fn write_interpretation_guide(md: &mut String) {
    md.push_str("## Interpretation Guide\n\n");
    md.push_str("### Effect Size (Cohen's d)\n\n");
    md.push_str("| Magnitude | Range | Interpretation |\n");
    md.push_str("|-----------|-------|----------------|\n");
    md.push_str("| Negligible | < 0.2 | Trivial effect |\n");
    md.push_str("| Small | 0.2 - 0.5 | Noticeable effect |\n");
    md.push_str("| Medium | 0.5 - 0.8 | Substantial effect |\n");
    md.push_str("| Large | > 0.8 | Dramatic effect |\n\n");

    md.push_str("### p-value\n\n");
    md.push_str("| Range | Interpretation |\n");
    md.push_str("|-------|----------------|\n");
    md.push_str("| < 0.001 | Highly significant |\n");
    md.push_str("| < 0.01 | Very significant |\n");
    md.push_str("| < 0.05 | Significant |\n");
    md.push_str("| ≥ 0.05 | Not significant |\n\n");
}

fn write_methodology(md: &mut String) {
    md.push_str("## Methodology\n\n");
    md.push_str("### Test Procedure\n\n");
    md.push_str("1. Run N simulations with Protocol ON (DecentralizedProtocol)\n");
    md.push_str("2. Run N simulations with Protocol OFF (CentralizedOracle)\n");
    md.push_str("3. Collect trust (τ) metrics from final simulation state\n");
    md.push_str("4. Compute Cohen's d effect size with 95% CI\n");
    md.push_str("5. Perform Welch's t-test for statistical significance\n\n");

    md.push_str("### Hypothesis Support Criteria\n\n");
    md.push_str("The hypothesis is supported if ALL of the following are true:\n\n");
    md.push_str("- Cohen's d ≥ 0.15 (practical significance threshold)\n");
    // TAG: surface=simulation owner=platform-team rule=GENERAL-001
    md.push_str("- p-value < 0.05 (statistical significance)\n");
    md.push_str("- 95% CI excludes zero (reliable effect)\n\n");
}

fn write_report_footer(md: &mut String, config: &ReportConfig) {
    md.push_str("---\n\n");
    let _ = writeln!(md, "*Generated by sim-report v{}*", config.version);
    md.push_str("*Per General Theory of Trust (GTT) validation protocol*\n");
}

/// Generate hypothesis testing report in Markdown
#[must_use]
pub fn hypothesis_template(report: &HypothesisReport) -> String {
    let mut md = String::new();
    write_hypothesis_header(&mut md, report);
    write_hypothesis_statement(&mut md);
    write_hypothesis_conclusion(&mut md, &report.result, &report.interpretation);
    write_results_summary(&mut md, &report.result, &report.interpretation);
    write_condition_comparison(&mut md, &report.result);
    write_statistical_interpretation(&mut md, &report.result, &report.interpretation);
    write_interpretation_guide(&mut md);
    write_methodology(&mut md);
    write_report_footer(&mut md, &report.config);
    md
}

fn write_full_header(md: &mut String, report: &FullSimulationReport) {
    let config = &report.config;
    let metadata = &report.metadata;
    let _ = write!(md, "# {}\n\n", config.title);
    let _ = write!(md, "## {}\n\n", metadata.description);
    let _ = write!(md, "**Simulation ID:** {}\n\n", metadata.simulation_id);
    let _ = write!(
        md,
        "**Generated:** {}\n\n",
        report.generated_at.format(&config.date_format)
    );
    let _ = write!(md, "**Author:** {}\n\n", config.author);
    let _ = write!(md, "**Institution:** {}\n\n", config.institution);
    let _ = write!(md, "**Version:** {}\n\n", config.version);
}

fn write_toc(md: &mut String, report: &FullSimulationReport) {
    md.push_str("## Table of Contents\n\n");
    md.push_str("1. [Executive Summary](#executive-summary)\n");
    md.push_str("2. [Simulation Configuration](#simulation-configuration)\n");
    if report.pom_validation.is_some() {
        md.push_str("3. [POM Validation Results](#pom-validation-results)\n");
    }
    // TAG: surface=simulation owner=research-team rule=SIM-001
    if report.hypothesis_test.is_some() {
        md.push_str("4. [GTT Hypothesis Test](#gtt-hypothesis-test)\n");
    }
    md.push_str("5. [Reproducibility Information](#reproducibility-information)\n");
    md.push_str("6. [Appendix](#appendix)\n\n");
}

fn write_executive_summary(md: &mut String, report: &FullSimulationReport) {
    md.push_str("## Executive Summary\n\n");

    if let Some(pom) = &report.pom_validation {
        let summary = &pom.summary;
        let _ = write!(
            md,
            "**POM Validation:** {}/{} targets passed ({:.1}%)\n\n",
            summary.passed,
            summary.total_targets,
            summary.pass_rate * 100.0
        );
    }

    if let Some(hyp) = &report.hypothesis_test {
        if hyp.result.hypothesis_supported {
            let _ = write!(
                md,
                "**GTT Hypothesis:** ✅ SUPPORTED (d={:.2}, p={:.4})\n\n",
                hyp.result.effect_size, hyp.result.p_value
            );
        } else {
            let _ = write!(
                md,
                "**GTT Hypothesis:** ❌ NOT SUPPORTED (d={:.2}, p={:.4})\n\n",
                hyp.result.effect_size, hyp.result.p_value
            );
        }
    }
}

